create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  author_name text not null check (char_length(trim(author_name)) between 1 and 120),
  comment text not null check (char_length(trim(comment)) between 1 and 4000),
  rating numeric(2,1) not null check (rating >= 1.0 and rating <= 5.0 and rating = trunc(rating))
);

alter table public.reviews enable row level security;

create policy "public can read reviews"
on public.reviews
for select
to public
using (true);

create policy "public can insert reviews"
on public.reviews
for insert
to public
with check (true);

create policy "authenticated can delete reviews"
on public.reviews
for delete
to authenticated
using ((select auth.uid()) is not null and coalesce((select auth.jwt()->>'is_anonymous'), 'false') = 'false' and exists (select 1 from public.authorized_users where email = lower((select auth.jwt()->>'email')) and role in ('staff', 'admin')));
